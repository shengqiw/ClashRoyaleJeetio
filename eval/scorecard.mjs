#!/usr/bin/env node
/**
 * The scorecard — jeetio's Deck AI eval suite. 18 fixed archetype lineups
 * ("holes") played against the live /api/deck-intel retrieval, scored like
 * golf: the opponent is your own last round.
 *
 * Per hole, six checks; strokes = 1 + misses (par 3, ace 1, blowup 7):
 *   answered   ≥1 counter deck came back
 *   valid      every returned deck is exactly 8 named cards
 *   relevant   ≥2 of the hole's query cards appear in some matchup's loserCards
 *              (did retrieval actually match the archetype, or return generic winners?)
 *   evidence   total occurrences across returned decks ≥ 3
 *   golden     ≥1 expected counter card appears in some returned winner deck
 *   fast       round-trip under 4s
 *
 * History is the source of truth in scorecard-history.json; scorecard.md is
 * regenerated from it every round. Both are committed — the trend IS the
 * artifact. Runs in CI on every master push (after the Vercel deploy) and
 * weekly; run locally with:
 *
 *   EVAL_BASE_URL=http://localhost:3000 node eval/scorecard.mjs
 *
 * Exits 1 when ≥6 holes are blowups — that's not a bad round, that's the
 * backend or the Pinecone index being down.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = dirname(fileURLToPath(import.meta.url));
const BASE = (process.env.EVAL_BASE_URL || "https://www.jeetio.com").replace(/\/$/, "");
const TIMEOUT_MS = 15000;
const PAR_PER_HOLE = 3;
const CHECKS = ["answered", "valid", "relevant", "evidence", "golden", "fast"];

/** Mirrors src/lib/useCardIcons.ts normalizeCardName — keep in sync. */
const norm = (name) =>
  String(name).toLowerCase().replace(/^(evo|evolved)\s+/, "").replace(/^the\s+/, "").replace(/[^a-z0-9]/g, "");

async function playHole(hole) {
  // Exact phrasing + topK the Counter-a-Deck feature sends (src/lib/deckIntel.ts).
  const body = { query: `Deck that beats this opponent deck: ${hole.cards.join(", ")}.`, topK: 5, band: hole.band };
  const started = Date.now();
  let counters = [];
  let error = null;
  try {
    const ctrl = new AbortController();
    const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
    const res = await fetch(`${BASE}/api/deck-intel`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body),
      signal: ctrl.signal,
    });
    clearTimeout(timer);
    const data = await res.json().catch(() => ({}));
    if (!res.ok) error = data?.error || `HTTP ${res.status}`;
    counters = Array.isArray(data?.counters) ? data.counters : [];
  } catch (e) {
    error = e?.name === "AbortError" ? `timeout ${TIMEOUT_MS}ms` : String(e?.message || e);
  }
  const ms = Date.now() - started;

  const queryNorms = hole.cards.map(norm);
  const expectNorms = (hole.expectAnyOf || []).map(norm);
  const misses = [];
  const answered = counters.length > 0;
  if (!answered) {
    // Nothing came back — every check is moot; that's the blowup hole.
    return { hole, strokes: 1 + CHECKS.length, misses: [...CHECKS], ms, error };
  }
  const valid = counters.every(
    (c) => Array.isArray(c.winnerCards) && c.winnerCards.length === 8 && c.winnerCards.every((n) => typeof n === "string" && n)
  );
  const relevant = counters.some((c) => {
    const losers = new Set((c.loserCards || []).map(norm));
    return queryNorms.filter((q) => losers.has(q)).length >= 2;
  });
  const evidence = counters.reduce((sum, c) => sum + (typeof c.occurrences === "number" ? c.occurrences : 1), 0) >= 3;
  const golden = counters.some((c) => (c.winnerCards || []).some((n) => expectNorms.includes(norm(n))));
  const fast = ms < 4000;

  for (const [check, ok] of [["answered", answered], ["valid", valid], ["relevant", relevant], ["evidence", evidence], ["golden", golden], ["fast", fast]]) {
    if (!ok) misses.push(check);
  }
  return { hole, strokes: 1 + misses.length, misses, ms, error };
}

function renderMarkdown(history, last) {
  const par = PAR_PER_HOLE * last.holes.length;
  const rows = history
    .map((r) => `| ${r.date} | ${r.sha} | ${r.strokes} | ${r.strokes - r.par >= 0 ? "+" : ""}${r.strokes - r.par} | ${r.aces} | ${r.blowups} |`)
    .join("\n");
  const detail = last.holes
    .map((h, i) => `| ${i + 1} | ${h.hole.name} | ${h.hole.band} | ${h.strokes} | ${h.ms}ms | ${h.misses.join(", ") || "—"} |`)
    .join("\n");
  return `# Deck AI Scorecard

18 fixed archetype lineups played against \`/api/deck-intel\` — the same call
Counter-a-Deck makes. Par ${PAR_PER_HOLE} a hole (${par} a round); strokes = 1 + failed
checks (answered / valid / relevant / evidence / golden / fast — see
\`eval/scorecard.mjs\`). The opponent is the last round. Regenerated by CI —
don't edit by hand.

## Rounds

| date | commit | strokes | ±par | aces | blowups |
|------|--------|---------|------|------|---------|
${rows}

## Last round — ${last.date} (${last.sha}) vs ${last.base}

| # | hole | band | strokes | rtt | missed checks |
|---|------|------|---------|-----|---------------|
${detail}
`;
}

const { holes } = JSON.parse(readFileSync(join(DIR, "holes.json"), "utf8"));
const results = [];
for (const hole of holes) {
  const r = await playHole(hole);
  results.push(r);
  console.log(
    `${String(results.length).padStart(2)}. ${hole.name.padEnd(24)} ${r.strokes} strokes` +
      ` (${r.ms}ms)${r.misses.length ? " missed: " + r.misses.join(",") : " ACE"}${r.error ? ` [${r.error}]` : ""}`
  );
}

const strokes = results.reduce((s, r) => s + r.strokes, 0);
const par = PAR_PER_HOLE * holes.length;
const aces = results.filter((r) => r.strokes === 1).length;
const blowups = results.filter((r) => r.misses.includes("answered")).length;
const round = {
  date: new Date().toISOString().slice(0, 10),
  sha: (process.env.GITHUB_SHA || "local").slice(0, 7),
  base: BASE,
  strokes,
  par,
  aces,
  blowups,
};

const historyPath = join(DIR, "scorecard-history.json");
let history = [];
try {
  history = JSON.parse(readFileSync(historyPath, "utf8"));
} catch {}
history.push(round);
writeFileSync(historyPath, JSON.stringify(history, null, 2) + "\n");
writeFileSync(join(DIR, "scorecard.md"), renderMarkdown(history, { ...round, holes: results }));

console.log(`\nRound: ${strokes} strokes vs par ${par} (${strokes - par >= 0 ? "+" : ""}${strokes - par}) · ${aces} aces · ${blowups} blowups`);
if (history.length > 1) {
  const prev = history[history.length - 2];
  const d = strokes - prev.strokes;
  console.log(`vs last round (${prev.date} ${prev.strokes}): ${d === 0 ? "even" : d > 0 ? `+${d} worse` : `${d} better`}`);
}
if (blowups >= 6) {
  console.error(`\n${blowups}/18 holes unanswered — that's an outage, not a bad round.`);
  process.exit(1);
}
